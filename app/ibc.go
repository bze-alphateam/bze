// registerIBCModules register IBC keepers and non dependency inject modules.
func (app *App) registerIBCModules(appOpts servertypes.AppOptions) error {
	// set up non depinject support modules store keys
	if err := app.RegisterStores(
		storetypes.NewKVStoreKey(ibcexported.StoreKey),
		storetypes.NewKVStoreKey(ibctransfertypes.StoreKey),
		storetypes.NewKVStoreKey(ratelimittypes.StoreKey),
		storetypes.NewKVStoreKey(icahosttypes.StoreKey),
		storetypes.NewKVStoreKey(icacontrollertypes.StoreKey),
		storetypes.NewTransientStoreKey(paramstypes.TStoreKey),
	); err != nil {
		return err
	}

	// register the key tables for legacy param subspaces
	keyTable := ibcclienttypes.ParamKeyTable()
	keyTable.RegisterParamSet(&ibcconnectiontypes.Params{})
	app.ParamsKeeper.Subspace(ibcexported.ModuleName).WithKeyTable(keyTable)
	app.ParamsKeeper.Subspace(ibctransfertypes.ModuleName).WithKeyTable(ibctransfertypes.ParamKeyTable())
	// the rate-limiting module's Params message is empty, so its subspace has no key table
	app.ParamsKeeper.Subspace(ratelimittypes.ModuleName)
	app.ParamsKeeper.Subspace(icacontrollertypes.SubModuleName).WithKeyTable(icacontrollertypes.ParamKeyTable())
	app.ParamsKeeper.Subspace(icahosttypes.SubModuleName).WithKeyTable(icahosttypes.ParamKeyTable())

	// Create IBC keeper
	app.IBCKeeper = ibckeeper.NewKeeper(
		app.appCodec,
		runtime.NewKVStoreService(app.GetKey(ibcexported.StoreKey)),
		app.GetSubspace(ibcexported.ModuleName),
		app.UpgradeKeeper,
		authtypes.NewModuleAddress(govtypes.ModuleName).String(),
	)

	// Register the proposal types
	// Deprecated: Avoid adding new handlers, instead use the new proposal flow
	// by granting the governance module the right to execute the message.
	// See: https://docs.cosmos.network/main/modules/gov#proposal-messages
	govRouter := govv1beta1.NewRouter()
	govRouter.AddRoute(govtypes.RouterKey, govv1beta1.ProposalHandler)

	// Create the rate-limiting keeper (cosmos/ibc-apps, used unmodified). It checks the
	// quotas of outgoing packets in its SendPacket and forwards them to the channel keeper.
	// Its only authority is the gov module account.
	app.RatelimitKeeper = *ratelimitkeeper.NewKeeper(
		app.appCodec,
		runtime.NewKVStoreService(app.GetKey(ratelimittypes.StoreKey)),
		app.GetSubspace(ratelimittypes.ModuleName),
		authtypes.NewModuleAddress(govtypes.ModuleName).String(),
		app.BankKeeper,
		app.IBCKeeper.ChannelKeeper,
		app.IBCKeeper.ClientKeeper,
		app.IBCKeeper.ChannelKeeper, // ICS4Wrapper
	)

	// x/guardian lowers the quotas through the rate-limiting keeper. It is built by
	// depinject before this keeper exists, so the keeper is handed over here.
	app.GuardianKeeper.SetRateLimitKeeper(app.RatelimitKeeper)
	// It checks that a transfer channel exists before closing it.
	app.GuardianKeeper.SetChannelKeeper(app.IBCKeeper.ChannelKeeper)

	// Create IBC transfer keeper. Outgoing transfer packets go through the closed-channel
	// gate (x/guardian channel switch), then the rate-limiting keeper (its ICS-4 wrapper),
	// on their way to the channel keeper. A send on a closed channel fails before any
	// quota is counted.
	app.TransferKeeper = ibctransferkeeper.NewKeeper(
		app.appCodec,
		runtime.NewKVStoreService(app.GetKey(ibctransfertypes.StoreKey)),
		app.GetSubspace(ibctransfertypes.ModuleName),
		txfeecollectoribc.NewSendGate(app.RatelimitKeeper, app.GuardianKeeper),
		app.IBCKeeper.ChannelKeeper,
		app.MsgServiceRouter(),
		app.AccountKeeper,
		app.BankKeeper,
		authtypes.NewModuleAddress(govtypes.ModuleName).String(),
	)

	// Create interchain account keepers
	app.ICAHostKeeper = icahostkeeper.NewKeeper(
		app.appCodec,
		runtime.NewKVStoreService(app.GetKey(icahosttypes.StoreKey)),
		app.GetSubspace(icahosttypes.SubModuleName),
		app.IBCKeeper.ChannelKeeper,
		app.IBCKeeper.ChannelKeeper,
		app.AccountKeeper,
		app.MsgServiceRouter(),
		app.GRPCQueryRouter(),
		authtypes.NewModuleAddress(govtypes.ModuleName).String(),
	)

	app.ICAControllerKeeper = icacontrollerkeeper.NewKeeper(
		app.appCodec,
		runtime.NewKVStoreService(app.GetKey(icacontrollertypes.StoreKey)),
		app.GetSubspace(icacontrollertypes.SubModuleName),
		app.IBCKeeper.ChannelKeeper,
		app.IBCKeeper.ChannelKeeper,
		app.MsgServiceRouter(),
		authtypes.NewModuleAddress(govtypes.ModuleName).String(),
	)
	app.GovKeeper.SetLegacyRouter(govRouter)

	// Create the transfer stack, from IBC core inward: rate-limiting middleware ->
	// txfeecollector inbound filter -> transfer application.
	// The txfeecollector inbound filter sits on top of the transfer application: it
	// answers packets listed in the BlockedIbcInbound param with an error
	// acknowledgement (see x/txfeecollector/ibcmiddleware). Only received packets are
	// affected - acks and timeouts pass straight through. The same middleware refuses
	// every packet received on a channel closed through x/guardian.
	// The rate-limiting middleware sits outside the filter: when the filter (or the
	// quota) answers with an error acknowledgement, the middleware only drops its
	// pending-packet marker. The inflow it counted is discarded because IBC core
	// commits the receive state changes only for a nil or successful acknowledgement,
	// so a refused packet never consumes quota.
	transferStack := porttypes.IBCModule(ibctransfer.NewIBCModule(app.TransferKeeper))
	transferStack = txfeecollectoribc.NewIBCMiddleware(transferStack, app.IBCKeeper.ChannelKeeper, app.TxfeecollectorKeeper, app.GuardianKeeper)
	transferStack = ratelimit.NewIBCMiddleware(app.RatelimitKeeper, transferStack)

	icaControllerIBCModule := icacontroller.NewIBCMiddleware(app.ICAControllerKeeper)
	icaHostIBCModule := icahost.NewIBCModule(app.ICAHostKeeper)

	// Create static IBC router, add transfer route, then set and seal it
	ibcRouter := porttypes.NewRouter().
		AddRoute(ibctransfertypes.ModuleName, transferStack).
		AddRoute(icacontrollertypes.SubModuleName, icaControllerIBCModule).
		AddRoute(icahosttypes.SubModuleName, icaHostIBCModule)

	// this line is used by starport scaffolding # ibc/app/module

	app.IBCKeeper.SetRouter(ibcRouter)

	// No IBC v2 application is wired. The empty v2 router makes v2 packets fail with
	// a missing route instead of reaching an unset router.
	app.IBCKeeper.SetRouterV2(ibcapi.NewRouter())

	// Light clients are routed explicitly since ibc-go v9: the two client types the
	// chain registered before keep working.
	clientKeeper := app.IBCKeeper.ClientKeeper
	storeProvider := clientKeeper.GetStoreProvider()

	tmLightClientModule := ibctm.NewLightClientModule(app.appCodec, storeProvider)
	clientKeeper.AddRoute(ibctm.ModuleName, &tmLightClientModule)

	smLightClientModule := solomachine.NewLightClientModule(app.appCodec, storeProvider)
	clientKeeper.AddRoute(solomachine.ModuleName, &smLightClientModule)

	// register IBC modules
	if err := app.RegisterModules(
		ibc.NewAppModule(app.IBCKeeper),
		ibctransfer.NewAppModule(app.TransferKeeper),
		ratelimit.NewAppModule(app.appCodec, app.RatelimitKeeper),
		icamodule.NewAppModule(&app.ICAControllerKeeper, &app.ICAHostKeeper),
		ibctm.NewAppModule(tmLightClientModule),
		solomachine.NewAppModule(smLightClientModule),
	); err != nil {
		return err
	}

	return nil
}

// RegisterIBC Since the IBC modules don't support dependency injection,
// we need to manually register the modules on the client side.
// This needs to be removed after IBC supports App Wiring.
func RegisterIBC(registry cdctypes.InterfaceRegistry) map[string]appmodule.AppModule {
	modules := map[string]appmodule.AppModule{
		ibcexported.ModuleName:      ibc.AppModule{},
		ibctransfertypes.ModuleName: ibctransfer.AppModule{},
		ratelimittypes.ModuleName:   ratelimit.AppModule{},
		icatypes.ModuleName:         icamodule.AppModule{},
		ibctm.ModuleName:            ibctm.AppModule{},
		solomachine.ModuleName:      solomachine.AppModule{},
	}

	for name, m := range modules {
		module.CoreAppModuleBasicAdaptor(name, m).RegisterInterfaces(registry)
	}

	return modules
}
